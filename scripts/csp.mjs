// Writes the Content-Security-Policy (and its companion headers) for nginx, from
// the built HTML. Runs after prerender, as the last step that touches dist/.
//
// The pre-paint boot script in index.html stays inline on purpose: it starts the
// session and `Me` requests in parallel with the bundle download, and an external
// file would put a render-blocking request in front of that. So instead of
// 'unsafe-inline', every inline script the build actually ships is allowed by its
// SHA-256, computed here from the final bytes (scripts/vite-plugin-boot-query.mjs
// rewrites that script at build time, so the hash cannot be written by hand).
// Any other inline script, e.g. one injected through an XSS, does not run.
//
// Output: dist-nginx/security-headers.conf, outside dist/ so it is never served.
// DockerfileProd copies it next to nginx.conf, which includes it in every
// location (nginx drops inherited add_header lines in any location that sets
// its own).
import { createHash } from 'node:crypto'
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const dist = resolve('dist')
const outDir = resolve('dist-nginx')

const EXECUTABLE_TYPES = new Set(['', 'text/javascript', 'application/javascript', 'module'])

function inlineScripts(html) {
  const scripts = []
  for (const match of html.matchAll(/<script(\s[^>]*)?>([\s\S]*?)<\/script>/gi)) {
    const attrs = match[1] ?? ''
    if (/\ssrc\s*=/i.test(attrs)) continue
    const type = (/\stype\s*=\s*["']?([^"'\s>]+)/i.exec(attrs)?.[1] ?? '').toLowerCase()
    if (!EXECUTABLE_TYPES.has(type)) continue // e.g. application/ld+json: data, never executed
    scripts.push(match[2])
  }
  return scripts
}

const hashes = new Set()
let pages = 0
for (const entry of readdirSync(dist, { withFileTypes: true, recursive: true })) {
  if (!entry.isFile() || !entry.name.endsWith('.html')) continue
  pages++
  const html = readFileSync(join(entry.parentPath ?? entry.path, entry.name), 'utf8')
  for (const script of inlineScripts(html)) {
    hashes.add(`'sha256-${createHash('sha256').update(script, 'utf8').digest('base64')}'`)
  }
}
if (pages === 0) throw new Error('csp: no HTML in dist/, run after vite build and prerender')

const policy = [
  "default-src 'self'",
  `script-src 'self' ${[...hashes].sort().join(' ')}`.trim(),
  // React style={...} attributes and Radix's positioning write inline styles.
  "style-src 'self' 'unsafe-inline'",
  // Avatars and app logos can come from anywhere (presigned storage URLs, social
  // account pictures); an image cannot run code.
  "img-src 'self' data: blob: https:",
  "font-src 'self' data:",
  // lok is same-origin (/lok/...); the app download picker asks GitHub for the
  // latest release (src/lib/appDownloads.ts).
  "connect-src 'self' https://api.github.com",
  "worker-src 'self' blob:",
  "frame-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  // Nothing but kontrol itself may frame it, the device-code /configure pages
  // included: their Approve button is exactly what clickjacking would target.
  "frame-ancestors 'self'",
  // No form-action: the OAuth consent form posts to lok, which redirects to the
  // relying party's registered redirect_uri, and browsers check form-action
  // against that redirect too.
].join('; ')

mkdirSync(outDir, { recursive: true })
writeFileSync(
  join(outDir, 'security-headers.conf'),
  [
    '# Generated by scripts/csp.mjs from the built HTML. Do not edit.',
    `add_header Content-Security-Policy "${policy}" always;`,
    // For browsers that predate frame-ancestors.
    'add_header X-Frame-Options "SAMEORIGIN" always;',
    'add_header X-Content-Type-Options "nosniff" always;',
    '',
  ].join('\n'),
)
console.log(`csp: ${hashes.size} inline script hash(es) from ${pages} page(s) -> dist-nginx/security-headers.conf`)
